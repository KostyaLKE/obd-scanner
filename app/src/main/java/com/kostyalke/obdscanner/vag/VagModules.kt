package com.kostyalke.obdscanner.vag

/** Блок управления VAG: адрес (как в VCDS, hex) и название. */
data class VagModule(val address: Int, val title: String) {
    /** Адреса ≥ 0x100 — блоки, найденные перебором TP2.0 без номера VCDS (TP-адрес = address − 0x100). */
    val addressText: String get() = if (address >= 0x100) "TP%02X".format(address - 0x100) else "%02X".format(address)
}

object VagModules {
    /** Основные блоки платформы PQ25 (Fabia II, Polo 6R, Ibiza 6J, Roomster). */
    val scanList = listOf(
        VagModule(0x01, "Двигатель"),
        VagModule(0x02, "Коробка передач"),
        VagModule(0x03, "ABS / ESP"),
        VagModule(0x08, "Климат / отопитель"),
        VagModule(0x09, "Центральная электроника"),
        VagModule(0x15, "Подушки безопасности"),
        VagModule(0x16, "Рулевая колонка"),
        VagModule(0x17, "Приборная панель"),
        VagModule(0x19, "Шлюз CAN"),
        VagModule(0x44, "Усилитель руля"),
        VagModule(0x46, "Комфорт"),
        VagModule(0x56, "Магнитола"),
    )

    /**
     * Расшифровки 5-значных кодов VAG (как в VCDS). Только хорошо известные;
     * остальные показываем номером — по нему легко найти описание.
     */
    private val known = mapOf(
        3 to "Блок управления неисправен",
        283 to "Датчик скорости вращения колеса передний левый (G47)",
        285 to "Датчик скорости вращения колеса передний правый (G45)",
        287 to "Датчик скорости вращения колеса задний правый (G44)",
        290 to "Датчик скорости вращения колеса задний левый (G46)",
        532 to "Напряжение питания (B+)",
        588 to "Пиропатрон подушки безопасности водителя (N95)",
        589 to "Пиропатрон подушки безопасности переднего пассажира (N131)",
        595 to "Записаны данные об аварии (crash data)",
        625 to "Сигнал скорости автомобиля",
        668 to "Напряжение питания, клемма 30",
        778 to "Датчик угла поворота руля (G85)",
        1044 to "Блок управления закодирован неправильно",
        1217 to "Пиропатрон боковой подушки водителя (N199)",
        1218 to "Пиропатрон боковой подушки переднего пассажира (N200)",
        1299 to "Диагностический интерфейс шины данных (J533)",
        1304 to "Магнитола: нет связи",
        1312 to "Шина данных силового агрегата",
        1314 to "Блок управления двигателем: нет связи",
        1316 to "Блок ABS: нет связи",
        1317 to "Блок управления в панели приборов (J285): нет связи",
        1321 to "Блок подушек безопасности (J234): нет связи",
        1330 to "Центральный блок комфорта (J393): нет связи",
    )

    fun describe(code: Int): String? = known[code]

    /**
     * Логические адреса TP2.0 (НЕ равны номерам VCDS!) — запасной вариант, если шлюз не отдал таблицу.
     * Подтверждено по открытым реализациям: 01 двигатель, 02 КПП, 03 ABS, 09 ГУР/EPS (VCDS 44),
     * 1F шлюз; 05 подушки — по одному источнику.
     */
    val tpFallback: Map<Int, Int> = mapOf(0x01 to 0x01, 0x02 to 0x02, 0x03 to 0x03, 0x44 to 0x09, 0x15 to 0x05, 0x19 to 0x1F)

    /** Перебор логических адресов, если шлюз молчит: так находятся и блоки, которых нет в таблице выше. */
    val tpProbe: List<Int> = (0x01..0x1F).toList()

    fun titleFor(vcds: Int): String = scanList.firstOrNull { it.address == vcds }?.title ?: "Блок %02X".format(vcds)

    /**
     * CAN-адреса UDS (запрос → ответ) для блоков VAG. Используются, если блок молчит на TP2.0:
     * более новые блоки (например, двигатель EDC17) общаются только по UDS.
     */
    val udsIds: Map<Int, Pair<Int, Int>> = mapOf(
        0x01 to (0x7E0 to 0x7E8),
        0x02 to (0x7E1 to 0x7E9),
        0x03 to (0x713 to 0x77D),
        0x08 to (0x746 to 0x7B0),
        0x09 to (0x70E to 0x778),
        0x15 to (0x715 to 0x77F),
        0x16 to (0x70C to 0x776),
        0x17 to (0x714 to 0x77E),
        0x19 to (0x710 to 0x77A),
        0x44 to (0x712 to 0x77C),
    )

    /**
     * Коды двигателя VAG 16384–19999 — это OBD-коды P0xxx/P1xxx в другой записи
     * (P0xxx → 16384 + xxx, P1xxx → 16408 + 1xxx).
     */
    fun toObdCode(code: Int): String? = when (code) {
        in 16384..17383 -> "P%04d".format(code - 16384)
        in 17408..18407 -> "P%04d".format(code - 16408)
        else -> null
    }

    fun format(code: Int): String = "%05d".format(code)
}
